/**
 * src/world/counterfactual.ts
 * Counterfactual Comparison Engine (With Plexus vs Without Plexus)
 *
 * Both columns are derived from the live World every tick — no pasted
 * constants. The WITHOUT column is a *modelled projection* (a counterfactual
 * cannot be measured): it re-evaluates the same demand with zero
 * cross-hospital coordination, i.e. every hospital left on its own stock.
 */

import { World } from './types';
import * as selectors from './selectors';

export interface ScenarioMetrics {
  openRequests: number;
  unmetUnits: number;
  serviceLevelPct: number | null;
  medianTimeToAssignMin: number | null;
  expiredUnits: number;
  rescuedUnits: number;
  outdateRatePct: number;
}

export interface ScenarioComparison {
  withPlexus: ScenarioMetrics;
  withoutPlexus: ScenarioMetrics;
}

/**
 * Requests generated by the scenario runner (`scn:` ids) or tagged as
 * simulated. The counterfactual is scoped to these when a scenario is live,
 * so baseline noise doesn't dilute the comparison.
 */
function getScopedRequests(world: World) {
  const all = Object.values(world.requests);
  const scenario = all.filter(
    (r) => r.id.startsWith('scn:') || r.sourceTag === 'Simulated scenario'
  );
  return scenario.length > 0 ? scenario : all;
}

/**
 * Computes live results comparison for WITH Plexus vs WITHOUT Plexus
 */
export function computeScenarioComparison(world: World): ScenarioComparison {
  const now = world.simNow;

  // ---------------------------------------------------------------------------
  // 1. WITH PLEXUS (Live Shared World Core)
  // ---------------------------------------------------------------------------
  const allRequests = Object.values(world.requests);

  let unmetUnitsWith = 0;
  for (const r of allRequests) {
    if (r.status === 'unfulfilled') {
      unmetUnitsWith += r.units;
    } else if ((r.status === 'requested' || r.status === 'matching') && now > r.neededBy) {
      unmetUnitsWith += r.units;
    }
  }

  // Service level: % fulfilled within window
  let fulfilledOnTimeWith = 0;
  const assignedWith = allRequests.filter(
    (r) => r.status !== 'requested' && r.status !== 'matching' && r.status !== 'unfulfilled' && r.status !== 'cancelled'
  );

  for (const r of assignedWith) {
    const orders = r.assignedOrderIds.map((id) => world.orders[id]).filter(Boolean);
    if (orders.length > 0) {
      const latestDelivered = Math.max(...orders.map((o) => o.deliveredAt));
      if (latestDelivered <= r.neededBy + 15 * 60000) {
        fulfilledOnTimeWith++;
      }
    }
  }

  const serviceLevelPctWith =
    allRequests.length > 0
      ? Math.round((fulfilledOnTimeWith / allRequests.length) * 100)
      : null;

  // Median time to assign — null until the first assignment exists
  const assignTimesMin: number[] = [];
  for (const r of assignedWith) {
    const orders = r.assignedOrderIds.map((id) => world.orders[id]).filter(Boolean);
    if (orders.length > 0) {
      const firstAssigned = Math.min(...orders.map((o) => o.assignedAt));
      const diffMin = Math.max(1, Math.round((firstAssigned - r.createdAt) / 60000));
      assignTimesMin.push(diffMin);
    }
  }

  assignTimesMin.sort((a, b) => a - b);
  const medianAssignMinWith =
    assignTimesMin.length > 0
      ? assignTimesMin[Math.floor(assignTimesMin.length / 2)]
      : null;

  // Rescued units (cross-hospital transfers of <36h shelf-life stock)
  const rescuedWith = selectors.getRescuedUnits(world);

  // Expired units: 30-day history + any lots already past expiry
  let expiredUnitsWith = 0;
  if (world.history30d) {
    for (const d of world.history30d) {
      expiredUnitsWith += d.expired;
    }
  }
  for (const lot of Object.values(world.lots)) {
    if (lot.expiresAt <= now) {
      expiredUnitsWith += lot.units;
    }
  }

  const outdateRateWith = Number((selectors.getOutdateRate(world) * 100).toFixed(1));

  // ---------------------------------------------------------------------------
  // 2. WITHOUT PLEXUS (modelled counterfactual: zero cross-hospital sharing)
  //
  // Every request is left to the requesting hospital's own usable stock
  // (incoming transfers ignored). Units the mesh actually rescued are the
  // surplus lots that would have expired in isolation.
  // ---------------------------------------------------------------------------
  const scopedRequests = getScopedRequests(world);

  let ownCoverableCount = 0;
  let unmetUnitsWithout = 0;
  for (const r of scopedRequests) {
    const ownUsable = selectors.getUsableUnits(world, r.hospital, r.group, r.product);
    if (ownUsable >= r.units) {
      ownCoverableCount++;
    } else {
      unmetUnitsWithout += r.units - ownUsable;
    }
  }

  // Monotonic guard (not a magic constant): an isolated network can never
  // outperform the coordinated optimum, so unmet WITHOUT >= unmet WITH.
  unmetUnitsWithout = Math.max(unmetUnitsWithout, unmetUnitsWith);

  const openRequestsWithout = scopedRequests.length;
  const serviceLevelPctWithout =
    scopedRequests.length > 0
      ? Math.round((ownCoverableCount / scopedRequests.length) * 100)
      : null;

  const medianAssignMinWithout = null; // nothing is ever assigned in isolation
  const rescuedWithout = 0; // no cross-hospital sharing exists

  // Without the mesh, every unit the network rescued expires in place
  const expiredUnitsWithout = expiredUnitsWith + rescuedWith;

  // Outdate rate over the same 30-day window selectors.getOutdateRate uses
  let totalReceived = 0;
  if (world.history30d) {
    for (const d of world.history30d) {
      totalReceived += d.received;
    }
  }
  const outdateRateWithout =
    totalReceived > 0
      ? Number(((expiredUnitsWithout / totalReceived) * 100).toFixed(1))
      : outdateRateWith;

  return {
    withPlexus: {
      openRequests: allRequests.filter((r) => r.status === 'requested' || r.status === 'matching').length,
      unmetUnits: unmetUnitsWith,
      serviceLevelPct: serviceLevelPctWith,
      medianTimeToAssignMin: medianAssignMinWith,
      expiredUnits: expiredUnitsWith,
      rescuedUnits: rescuedWith,
      outdateRatePct: outdateRateWith,
    },
    withoutPlexus: {
      openRequests: openRequestsWithout,
      unmetUnits: unmetUnitsWithout,
      serviceLevelPct: serviceLevelPctWithout,
      medianTimeToAssignMin: medianAssignMinWithout,
      expiredUnits: expiredUnitsWithout,
      rescuedUnits: rescuedWithout,
      outdateRatePct: outdateRateWithout,
    },
  };
}
